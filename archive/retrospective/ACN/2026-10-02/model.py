def legacy_tier(rb):
    if rb < 0.75: return "BUY", "◉ BUY"
    if rb < 1.10: return "ACCUMULATE", "◎ ACCUMULATE"
    if rb < 1.75: return "WATCHLIST", "◐ WATCHLIST"
