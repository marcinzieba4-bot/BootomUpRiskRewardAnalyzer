def score_signal(val, base_f, bull_f, xbull_f, hib):
    if val is None:                       # no published value: BASE
        return 2
    if hib:
        if val >= xbull_f: return 4
        if val >= bull_f:  return 3
        if val >= base_f:  return 2
        return 1
    else:
        if val <= xbull_f: return 4
        if val <= bull_f:  return 3
        if val <= base_f:  return 2
        return 1

