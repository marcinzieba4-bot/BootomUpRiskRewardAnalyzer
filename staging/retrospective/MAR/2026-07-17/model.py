def _cagr(a, b, years):
    return (b / a) ** (1 / years) - 1

def _median(v):
    v = sorted(v); n = len(v)
    return v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2

def _pct_range(lo, hi):
    return f"{lo:+g}%" if lo == hi else f"+{lo:g}-{hi:g}%" if lo >= 0 else f"{lo:+g}% to {hi:+g}%"   # "+6%", "+6-7%", "-1% to +1%"

def _ordinal(n):
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"

def _now(v, u):
    return "n/r" if v is None else f"{v:+.1f}{u}"   # n/r: not reported (no figure in the filings public on AS_OF)

